"""A project's own copy of the person's know-how, in `.athos/`, that every agent reads without Athos installed.

    athos project sync            the pieces this project used (or is tagged with) → .athos/
    athos project sync --all      every piece;  --piece ID (repeatable) only those
    athos project remove          take .athos/ and every pointer to it out of the project

`.athos/` holds the wiki (Index.md, the pages, METHOD.md: how the trajectories were made), the trajectory subagents,
one skill per page and a `tools/` folder for the code the pages call. Each agent then gets a thin pointer it already
reads, so the same markdown reaches all of them:

    Claude Code   .claude/skills/athos-<id>, .claude/agents/athos-*.md, a block in CLAUDE.md
    Codex         .agents/skills/athos-<id>, a block in AGENTS.md
    Muse Code     .agents/skills (it also reads .claude/skills and skips the duplicate), AGENTS.md
    OpenCode      .agents/ and .claude/skills, .opencode/agents/athos-*.md, AGENTS.md

The person's store (`~/.athos`) stays the source: `.athos/` is a view of it, rebuilt by `sync`. It goes into
`.gitignore` unless the person asks to share it (`--commit`): know-how written in an employer's repository would stay
there when the person leaves.
"""

from __future__ import annotations

import re
import shutil
from pathlib import Path

from athos import eval as ev, paths, store, wiki
from athos.adapters import codex

DIR = ".athos"
PREFIX = "athos-"
BEGIN, END = "<!-- athos:begin -->", "<!-- athos:end -->"
MARK = "Generated by `athos project sync`"
IGNORE = [f"{DIR}/", f".claude/skills/{PREFIX}*", f".claude/agents/{PREFIX}*", f".agents/skills/{PREFIX}*",
          f".opencode/agents/{PREFIX}*"]
NEGATIVE = re.compile(r"^\s*(never|don'?t|do not|no |nunca|no hay que|jamás)", re.IGNORECASE)


def select(root: Path, ids: list[str] | None = None, everything: bool = False) -> list[store.Piece]:
    """The pieces that belong in this project: the ones named, every piece, or those tagged with the project or
    loaded or saved by one of its tasks."""
    pieces = store.all_pieces()
    if ids:
        missing = sorted(set(ids) - {p.id for p in pieces})
        if missing:
            raise LookupError(f"no piece {', '.join(missing)}")
        return [p for p in pieces if p.id in ids]
    if everything:
        return pieces
    name = paths.project_of(root)
    used = {pid for t in ev.tasks() if t.get("project") == name for pid in t["pieces"] + t["saved"]}
    return [p for p in pieces if name in p.projects or p.id in used]


# ------------------------------------------------------------------------------------------------ texts
def readme_text(name: str, pieces: list[store.Piece]) -> str:
    return "\n".join([
        f"# Know-how for {name}", "",
        f"<!-- {MARK}: edit the pages in ~/.athos/know-how, then sync again. -->", "",
        "How this work is done, written as markdown any AI agent can follow. It came from real tasks: each page was",
        "saved and improved while someone worked with an agent, and says when each step applies, what to do and why.",
        "", "| Folder | What it is |", "|---|---|",
        "| `wiki/` | The pages, `Index.md` (where a task starts) and `METHOD.md` (how the pages and their trajectories "
        "were made) |",
        "| `agents/` | One subagent per trajectory: a walk through the pages, in order. `AGENTS.md` lists them |",
        "| `skills/` | One skill per page, in the format Claude Code, Codex, Muse Code and OpenCode read. `SKILLS.md` "
        "lists them |",
        "| `tools/` | Code the pages call when a step is a calculation, not a judgement |", "",
        "Each agent reads it from where it already looks: `.claude/skills` and `CLAUDE.md` (Claude Code),",
        "`.agents/skills` and `AGENTS.md` (Codex, Muse Code, OpenCode), `.claude/agents` and `.opencode/agents`",
        "(subagents). Those copies are rebuilt by `athos project sync` and removed by `athos project remove`.", "",
        f"{len(pieces)} page(s): " + ", ".join(f"`{p.id}` v{p.version}" for p in pieces) + ".", ""])


def method_text(pieces: list[store.Piece], trails: dict[str, list[str]]) -> str:
    """How the trajectories of this knowledge base were made, and where each page came from."""
    out = ["# Method", "",
           f"<!-- {MARK}. -->", "",
           "## How a page is made", "",
           "- A page is saved at the end of a real task, when it taught something reusable: how it was solved, the",
           "  criteria, the steps, the mistakes avoided. The person's corrections during the task go in as steps.",
           "- A page is a list of **statements**, the smallest unit you can check: **When** (the moment in the task it",
           "  applies, as you would recognise it mid-task), **Do** (an action concrete enough to check: a command, a",
           "  file, a question to the person, a refusal), **Because** (the reason or the evidence), **Links**.",
           "- The person's exact conventions stay verbatim: names, formats, paths, flags.",
           "- Every improvement is a new version; the earlier one is kept, and the history line says what changed.", "",
           "## How a trajectory is made", "",
           "- A link points to the statement that was applied **right after it, or together with it, in a real task**,",
           "  never to a page on the same topic. Following links is doing the task again.",
           "- A walk starts at the page `Index.md` names for the situation, takes its first statement and follows",
           "  links while their **When** applies. A walk that reaches more than one page is a trajectory, and each",
           "  trajectory is a subagent in `agents/`.",
           "- A link nobody follows again is a candidate to drop when the page is next improved.", "",
           "## What not to do", "",
           "Steps that forbid something, gathered here because they are the easiest to forget:", ""]
    negatives = [(p, s) for p in pieces for s in wiki.statements(p) if s.do and NEGATIVE.match(s.do)]
    out += [f"- [[{s.ref}]]: {s.do}" for p, s in negatives] or ["- (none yet)"]
    out += ["", "## Where each page came from", ""]
    for p in pieces:
        o = p.origin or {}
        made = " · ".join(x for x in (o.get("platform"), o.get("model")) if x)
        out += [f"### {p.title} (`{p.id}`, v{p.version})", "",
                f"- When: {p.when}",
                f"- Created {p.created or '?'}" + (f" in {made}" if made else "") + f"; last used {p.last_used or '?'}.",
                f"- {len([s for s in wiki.statements(p) if s.id != 'steps'])} statement(s)."]
        out += [f"- {h.lstrip('- ').strip()}" for h in p.history]
        out.append("")
    if trails:
        out += ["## Trajectories", ""]
        out += ["- " + " → ".join(f"`{pid}`" for pid in t) for t in trails.values()]
        out.append("")
    return "\n".join(out)


def skill_text(p: store.Piece) -> str:
    return codex.skill_text(p).replace("Generated by `athos export --codex`", MARK, 1)


def agent_files(pieces: list[store.Piece]) -> dict[str, str]:
    """One subagent per trajectory, and one per page no trajectory covers, so every entry point has one."""
    pages = {p.id: p for p in pieces}
    trails = wiki.trajectories(pieces)
    covered = {pid for t in trails.values() for pid in t}
    walks = dict(trails)
    walks.update({p.id: [p.id] for p in pieces if p.id not in covered})
    return {f"{PREFIX}{start}.md": wiki.agent_text(trail, pages).replace("Generated by Athos", MARK, 1)
            for start, trail in sorted(walks.items())}


def opencode_agent(text: str) -> str:
    """OpenCode's subagent format: a description and `mode: subagent`; it names the agent after the file."""
    head, _, body = text.partition("\n---\n")
    desc = next((ln for ln in head.splitlines() if ln.startswith("description:")), "description: ''")
    return f"---\n{desc}\nmode: subagent\n---\n{body}"


def pointer_text(names: list[str]) -> str:
    return "\n".join([
        BEGIN,
        "## Know-how (Athos)", "",
        "This project keeps how its work is done in `.athos/`. Before a task, read `.athos/wiki/Index.md`, follow the",
        "page it names for the situation, and say in one line which page you follow and how it applies here. Each page",
        "is also a skill (`athos-<page>`)" + (", and each trajectory a subagent" if names else "") + ".",
        END])


# ------------------------------------------------------------------------------------------------ files
def _replace_block(path: Path, block: str | None) -> bool:
    """Put Athos's block in a file (or take it out with None), leaving the rest as it was. Returns whether it changed."""
    old = path.read_text() if path.exists() else ""
    rest = re.sub(rf"\n*{re.escape(BEGIN)}.*?{re.escape(END)}\n*", "\n\n", old, flags=re.S).strip("\n")
    if block:
        new = (rest + "\n\n" if rest else "") + block + "\n"
    else:
        new = rest + "\n" if rest else ""
    if new == old:
        return False
    if new:
        path.write_text(new)
    else:
        path.unlink()
    return True


def _write_dir(dest: Path, files: dict[str, str], glob: str) -> None:
    """Write Athos's files into a folder and remove Athos's older ones there; never touch anyone else's."""
    dest.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        f = dest / name
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(text)
    keep = {Path(n).parts[0] for n in files}
    for f in dest.glob(glob):
        if f.name in keep:
            continue
        target = f / "SKILL.md" if f.is_dir() else f
        if target.is_file() and MARK in target.read_text():
            shutil.rmtree(f) if f.is_dir() else f.unlink()


def _ignore(root: Path, add: bool) -> None:
    gi = root / ".gitignore"
    lines = gi.read_text().splitlines() if gi.exists() else []
    head = "# Athos: the person's know-how, rebuilt by `athos project sync`"
    kept = [ln for ln in lines if ln not in IGNORE and ln != head]
    while kept and not kept[-1].strip():
        kept.pop()
    if add:
        kept += ([""] if kept else []) + [head] + IGNORE
    if kept == lines:
        return
    if kept:
        gi.write_text("\n".join(kept) + "\n")
    else:
        gi.unlink()


def sync(root: Path, ids: list[str] | None = None, everything: bool = False, commit: bool = False) -> dict:
    """Build `.athos/` from the person's store and point every agent at it. Returns what was written."""
    root = root.resolve()
    pieces = select(root, ids, everything)
    if not pieces:
        raise LookupError(f"no piece is tagged with or was used in {paths.project_of(root)}: "
                          "name some with --piece, or use --all")
    pages = {p.id: p for p in pieces}
    trails = wiki.trajectories(pieces)
    base = root / DIR
    if base.exists():
        shutil.rmtree(base)
    (base / "wiki").mkdir(parents=True)
    for p in pieces:
        (base / "wiki" / f"{p.id}.md").write_text(store.render(p))
    (base / "wiki" / wiki.INDEX).write_text(wiki.index_text(pieces))
    (base / "wiki" / "METHOD.md").write_text(method_text(pieces, trails))
    agents = agent_files(pieces)
    skills = {f"{PREFIX}{p.id}/SKILL.md": skill_text(p) for p in pieces}
    _write_dir(base / "agents", agents, f"{PREFIX}*.md")
    (base / "agents" / "AGENTS.md").write_text("\n".join(
        ["# Subagents", "", f"<!-- {MARK}. -->", "",
         "Each one walks one trajectory of this project's know-how, in order, and cites every statement it follows.",
         ""] + [f"- `{n[:-3]}`: " + " → ".join(pages[pid].title for pid in (trails.get(n[len(PREFIX):-3])
                                                                          or [n[len(PREFIX):-3]])) for n in agents]
        + [""]))
    _write_dir(base / "skills", skills, f"{PREFIX}*")
    (base / "skills" / "SKILLS.md").write_text("\n".join(
        ["# Skills", "", f"<!-- {MARK}. -->", "", "One per page; an agent loads one when a request matches its "
         "description.", ""] + [f"- `{PREFIX}{p.id}` ← `wiki/{p.id}.md` v{p.version}: {p.when}" for p in pieces]
        + [""]))
    tools = base / "tools"
    tools.mkdir()
    (tools / "README.md").write_text(f"# Tools\n\n<!-- {MARK}. -->\n\nCode the pages call when a step is a "
                                     "calculation or a check rather than a judgement (totals, dates, tables, "
                                     "validation). Keep each script small and name it in the step that runs it.\n")
    (base / "README.md").write_text(readme_text(paths.project_of(root), pieces))
    # Pointers where each agent already looks.
    _write_dir(root / ".claude" / "skills", skills, f"{PREFIX}*")
    _write_dir(root / ".agents" / "skills", skills, f"{PREFIX}*")
    _write_dir(root / ".claude" / "agents", agents, f"{PREFIX}*.md")
    _write_dir(root / ".opencode" / "agents", {n: opencode_agent(t) for n, t in agents.items()}, f"{PREFIX}*.md")
    block = pointer_text(list(agents))
    _replace_block(root / "AGENTS.md", block)
    _replace_block(root / "CLAUDE.md", block)
    _ignore(root, add=not commit)
    return {"root": str(base), "pieces": [p.id for p in pieces], "agents": sorted(agents),
            "skills": sorted(skills), "ignored": not commit}


def remove(root: Path) -> list[str]:
    """Take `.athos/` and every copy and block Athos put in the project out of it. Returns what was removed."""
    root = root.resolve()
    gone = []
    if (root / DIR).exists():
        shutil.rmtree(root / DIR)
        gone.append(DIR)
    for d, glob in ((".claude/skills", f"{PREFIX}*"), (".agents/skills", f"{PREFIX}*"),
                    (".claude/agents", f"{PREFIX}*.md"), (".opencode/agents", f"{PREFIX}*.md")):
        if (root / d).is_dir():
            before = set((root / d).iterdir())
            _write_dir(root / d, {}, glob)
            gone += [f"{d}/{f.name}" for f in before - set((root / d).iterdir())]
    gone += [f for f in ("AGENTS.md", "CLAUDE.md") if _replace_block(root / f, None)]
    _ignore(root, add=False)
    return gone
