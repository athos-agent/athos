"""Athos inside OpenAI's Codex, reading the very same store under `~/.athos` (there is never a Codex-only copy).

Codex can reach the know-how by two routes:

* Hooks (`athos codex install`). Athos registers itself in Codex's `hooks.json` for four moments: the start of a
  session (the index), each prompt (the pieces that match it), each tool call and the end of a turn (capture and the
  evaluation records, tagged platform = codex). Codex asks once, through `/hooks`, before it trusts new hooks.
* Skills (`athos export --codex`). Every piece is translated into `~/.agents/skills/athos-<id>/SKILL.md`; Codex opens
  one only when a request fits its description. The translation keeps the whole piece, and the store remains the
  single source of truth.

This module also reads Codex's own session logs ("rollouts"): for the token cost of a task, and to import past turns
into the evaluation log. Rollouts carry running totals of tokens, so a task's cost is its last total minus the total
reported just before it began.
"""

from __future__ import annotations

import contextlib
import datetime as _dt
import json
import os
import re
import shutil
from pathlib import Path
from typing import Iterator

from athos import paths as athos_paths, store

# Codex hook event -> the `athos hook` moment that handles it.
EVENTS = {
    "SessionStart": "session-start",
    "UserPromptSubmit": "prompt",
    "PostToolUse": "tool",
    "Stop": "stop",
}
MARK = "athos hook"            # every command Athos writes into hooks.json contains this...
_PLATFORM_FLAG = "--platform codex"   # ...and this, which tells ours apart from Claude Code's
SKILL_PREFIX = "athos-"
_EXPORT_STAMP = "Generated by `athos export --codex`"


# ======================================================================================================== locations
def codex_home() -> Path:
    """Codex's configuration folder: `$CODEX_HOME` when set, `~/.codex` otherwise."""
    configured = os.environ.get("CODEX_HOME")
    return Path(configured) if configured else Path.home() / ".codex"


def skills_dir() -> Path:
    """The shared skills folder Codex and Muse Code both scan; tests point `ATHOS_SKILLS_DIR` elsewhere."""
    configured = os.environ.get("ATHOS_SKILLS_DIR")
    return Path(configured) if configured else Path.home() / ".agents" / "skills"


def sessions_dir() -> Path:
    """Where Codex keeps its rollouts, one JSONL file (possibly zstd-compressed) per session."""
    return codex_home() / "sessions"


def _hooks_file(given: Path | None) -> Path:
    return given if given is not None else codex_home() / "hooks.json"


# ======================================================================================================== the shim
# Codex stores a fixed command per hook, but the Claude Code plugin lives in a versioned folder that moves on every
# update. So the hooks call this small launcher instead, and it picks the right Athos each time it runs.
# `athos.connect.command_version` reads launchers already on disk: it looks for the "Runs the newest installed Athos"
# docstring and for the quoted fallback after `cands[-1] if cands else`, so both must stay exactly as they are.
_SHIM = '''#!/usr/bin/env python3
"""Runs the newest installed Athos; the file comes from `athos codex install` or `athos opencode install`."""
import glob
import os
import sys

PLUGINS = "~/.claude/plugins/cache/athos/athos/*/bin/athos"


def version_key(launcher):
    folder = launcher.split("/")[-3]            # .../athos/athos/<version>/bin/athos
    return [int(part) if part.isdigit() else part for part in folder.replace("-", ".").split(".")]


def pick():
    if os.environ.get("ATHOS_ROOT"):
        return os.path.join(os.environ["ATHOS_ROOT"], "bin", "athos")
    cands = sorted(glob.glob(os.path.expanduser(PLUGINS)), key=version_key)
    return cands[-1] if cands else __FALLBACK__


launcher = pick()
sys.argv[0] = launcher
sys.path.insert(0, os.path.dirname(os.path.dirname(launcher)))
from athos.cli import main
raise SystemExit(main())
'''


def shim_path() -> Path:
    """The launcher's fixed location inside the Athos home."""
    return athos_paths.home().joinpath("bin", "athos")


def write_shim(root: Path) -> Path:
    """(Re)write the launcher every Codex and OpenCode hook goes through. It prefers `$ATHOS_ROOT`, then the newest
    Claude Code plugin install, and finally `root`, the Athos copy doing the installing. Returns its path."""
    target = shim_path()
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(_SHIM.replace("__FALLBACK__", repr(str(root / "bin" / "athos"))))
    target.chmod(0o755)
    return target


# ======================================================================================================== hooks.json
def _hook_command(shim: Path, moment: str) -> str:
    return f"python3 {shim} hook {moment} {_PLATFORM_FLAG}"


def _is_ours(handler: dict) -> bool:
    """True for a hooks.json handler Athos wrote for Codex."""
    command = str(handler.get("command", ""))
    return MARK in command and _PLATFORM_FLAG in command


def _read_hooks(file: Path) -> dict:
    return json.loads(file.read_text() or "{}")


def _write_hooks(file: Path, data: dict) -> None:
    file.parent.mkdir(parents=True, exist_ok=True)
    file.write_text(json.dumps(data, indent=2) + "\n")


def _back_up(file: Path) -> Path:
    """Copy `file` next to itself, stamped with the current time, and return the copy."""
    copy = file.with_name(f"hooks.json.bak-{_dt.datetime.now():%Y%m%d-%H%M%S}")
    shutil.copy2(file, copy)
    return copy


def _drop_ours(config: dict) -> dict:
    """Strip Athos's handlers from a parsed hooks.json, in place. A group left with no handlers is dropped, and so is
    an event left with no groups; whatever belongs to someone else is untouched."""
    events = config.get("hooks", {})
    for event, groups in list(events.items()):
        remaining = []
        for group in groups:
            foreign = [h for h in group.get("hooks", []) if not _is_ours(h)]
            if foreign:
                remaining.append({**group, "hooks": foreign})
        if remaining:
            events[event] = remaining
        else:
            del events[event]
    return config


def install(root: Path, hooks_file: Path | None = None) -> tuple[Path, Path | None]:
    """Register Athos in Codex's hooks.json alongside any hooks already there; running it twice changes nothing.
    Returns the hooks file and a timestamped backup of what it held before (None if it did not exist)."""
    target = _hooks_file(hooks_file)
    launcher = write_shim(root)                         # before touching hooks.json, as the handlers point at it
    backup = None
    current: dict = {}
    if target.is_file():
        current = _read_hooks(target)
        backup = _back_up(target)
    data = _drop_ours(current)
    events = data.setdefault("hooks", {})
    for event, moment in EVENTS.items():
        handler = {"type": "command", "command": _hook_command(launcher, moment)}
        events.setdefault(event, []).append({"hooks": [handler]})
    _write_hooks(target, data)
    return target, backup


def installed() -> bool:
    """Whether Codex runs Athos: through hooks in its hooks.json or as a plugin in its plugin cache."""
    home = codex_home()
    hooks_text = ""
    with contextlib.suppress(OSError):                  # no hooks.json yet, or unreadable
        hooks_text = (home / "hooks.json").read_text()
    return "athos" in hooks_text or any((home / "plugins" / "cache").glob("*/athos"))


def uninstall(hooks_file: Path | None = None) -> bool:
    """Take Athos's handlers out of hooks.json. False when there is no hooks file to clean."""
    target = _hooks_file(hooks_file)
    present = target.is_file()
    if present:
        _write_hooks(target, _drop_ours(_read_hooks(target)))
    return present


# ======================================================================================================== skills
def _skill_name(piece_id: str) -> str:
    return f"{SKILL_PREFIX}{piece_id}"


def skill_text(piece: store.Piece) -> str:
    """Render a piece as a SKILL.md. Codex decides when to load a skill from its description alone, so that line
    carries the title and the piece's "when"; below the header comes the complete piece, frontmatter and history."""
    description = f"{piece.title}. Use when: {piece.when}".replace("\n", " ")
    header = "\n".join(["---", f"name: {_skill_name(piece.id)}", f"description: {store._quote(description)}", "---"])
    notice = f"<!-- {_EXPORT_STAMP} from {piece.path}. Edit the piece, not this file. -->"
    return f"{header}\n\n{notice}\n\n{store.render(piece)}"


def _exported_by_us(folder: Path) -> bool:
    """A skill folder this exporter created (other tools' skills may share the prefix)."""
    skill = folder / "SKILL.md"
    return folder.is_dir() and skill.is_file() and "athos export --codex" in skill.read_text()


def export_skills(dest: Path | None = None) -> tuple[int, int]:
    """Mirror the store into a skills folder: one skill per piece, and the skills of deleted pieces removed.
    Returns (skills written, skills removed)."""
    target = dest or skills_dir()
    target.mkdir(parents=True, exist_ok=True)
    current = set()
    for piece in store.all_pieces():
        folder = target / _skill_name(piece.id)
        folder.mkdir(exist_ok=True)
        (folder / "SKILL.md").write_text(skill_text(piece))
        current.add(folder.name)
    stale = [f for f in target.glob(f"{SKILL_PREFIX}*") if f.name not in current and _exported_by_us(f)]
    for folder in stale:
        shutil.rmtree(folder)
    return len(current), len(stale)


# ======================================================================================================== rollouts
def _open_rollout(path: str):
    """Open a rollout as text. Codex compresses older ones to `<name>.zst`, so a plain path that no longer exists is
    looked up with that suffix. Raises OSError (or ImportError without zstd support), like `open`."""
    compressed = path if path.endswith(".zst") else path + ".zst"
    if path == compressed or (not os.path.exists(path) and os.path.exists(compressed)):
        import compression.zstd as zstd_codec            # Python 3.14+; an ImportError tells the caller it is missing
        return zstd_codec.open(compressed, "rt", errors="ignore")
    return open(path, "rt", errors="ignore")


def _moment(value) -> _dt.datetime | None:
    """An ISO-8601 timestamp (Codex writes them with a trailing Z) as a datetime; None for anything else."""
    stamp = None
    if isinstance(value, str):
        with contextlib.suppress(ValueError):
            stamp = _dt.datetime.fromisoformat(value.replace("Z", "+00:00"))
    return stamp


def _records(path: str, needle: str | None = None) -> Iterator[tuple[str, dict]]:
    """Each JSON object of a rollout with its raw line, skipping lines that are not JSON objects. With `needle`, only
    lines containing it are parsed. Yields nothing when the file cannot be opened."""
    handle = None
    with contextlib.suppress(OSError, ImportError):     # missing, unreadable, or .zst without zstd support
        handle = _open_rollout(path)
    if handle is None:
        return
    with handle:
        wanted = (line for line in handle if needle is None or needle in line)
        for line in wanted:
            record = _json_object(line)
            if record is not None:
                yield line, record


def _json_object(line: str) -> dict | None:
    parsed = None
    with contextlib.suppress(ValueError):
        parsed = json.loads(line)
    return parsed if isinstance(parsed, dict) else None


def _payload(record: dict) -> dict:
    body = record.get("payload")
    return body if isinstance(body, dict) else {}


def _cumulative_usage(record: dict) -> dict | None:
    """The running token totals a `token_count` event reports, if this record is one."""
    body = _payload(record)
    is_report = body.get("type") == "token_count"
    return (body.get("info") or {}).get("total_token_usage") if is_report else None


def _usage_delta(end: dict, start: dict) -> dict:
    """Turn two running totals into the tokens spent in between, in Athos's token fields."""
    def spent(field):
        return int(end.get(field) or 0) - int(start.get(field) or 0)

    cache_read = spent("cached_input_tokens")
    tokens = {
        "input": spent("input_tokens") - cache_read,    # Codex counts cached input inside input_tokens
        "output": spent("output_tokens"),
        "cache_read": cache_read,
        "cache_write": spent("cache_write_input_tokens"),
    }
    tokens["total"] = spent("total_tokens") or sum(tokens.values())
    return tokens


def tokens_between(rollout: str | None, start: str, end: str) -> dict | None:
    """What Codex spent between `start` and `end` (ISO times), from a rollout: the last running total reported by
    `end`, minus the last one reported before `start`. None if the rollout is missing or unreadable, or reports
    nothing inside the window."""
    since, until = _moment(start), _moment(end)
    baseline, latest = None, None
    reports = _records(rollout, needle='"token_count"') if rollout else ()
    for _, record in reports:
        usage = _cumulative_usage(record)
        when = _moment(record.get("timestamp", ""))
        if not usage or when is None:
            pass                                          # not a usage report, or one we cannot place in time
        elif since and when < since:
            baseline = usage
        elif until is None or when <= until:
            latest = usage
    return None if latest is None else _usage_delta(latest, baseline or {})


# ======================================================================================================== import
SKILL_USE = re.compile(r"athos-([a-z0-9][a-z0-9-]*)/SKILL\.md")          # a skill file being read
INJECTED = re.compile(r"<(environment_context|user_instructions|INSTRUCTIONS)>.*?</\1>", re.S)  # Codex's own context
HOOK_USE = re.compile(r"\(`([a-z0-9][a-z0-9-]*)`, v\d+\)")              # a piece the hooks put in the prompt
TMP_PREFIXES = ("/tmp/", "/private/tmp/", "/var/folders/")   # where test runs live
_IMPORTED = "cx-"                                           # task ids of imported turns start with this


def _user_words(body: dict) -> str:
    """The text of a user message minus the context blocks Codex adds to it."""
    parts = [part.get("text", "") for part in body.get("content") or [] if isinstance(part, dict)]
    return INJECTED.sub("", " ".join(parts)).strip()


def _is_catalog(record: dict) -> bool:
    """Codex repeats the list of available skills (paths included) in `world_state` and in a developer or system
    message every turn. Naming a skill there does not mean it was used."""
    body = _payload(record)
    listed_by_codex = body.get("type") == "message" and body.get("role") in ("developer", "system")
    return record.get("type") == "world_state" or (record.get("type") == "response_item" and listed_by_codex)


class _TurnReader:
    """Walks one rollout and collects its finished turns (from `task_started` to `task_complete`)."""

    def __init__(self) -> None:
        self.meta: dict = {}
        self.model = "unknown"
        self.pending_request = ""     # what the person said before a turn opened
        self.turn: dict | None = None
        self.done: list[dict] = []

    def feed(self, line: str, record: dict) -> None:
        body = _payload(record)
        source, event = record.get("type"), body.get("type")
        if source == "session_meta":
            self.meta = body
        elif source == "turn_context":
            self.model = body.get("model") or self.model
            if self.turn is not None:
                self.turn["model"] = self.model
        elif source == "response_item" and event == "message" and body.get("role") == "user":
            words = _user_words(body)
            if not words:
                return                # nothing but injected context
            if self.turn is not None and not self.turn["request"]:
                self.turn["request"] = words      # recent Codex writes the request after the turn opens
            else:
                self.pending_request = words
        elif source == "event_msg" and event == "task_started":
            self.turn = {"turn_id": body.get("turn_id"), "started": record.get("timestamp"), "model": self.model,
                         "request": self.pending_request, "pieces": set()}
        elif source == "event_msg" and event == "task_complete" and self.turn is not None:
            millis = int(body.get("duration_ms") or 0)
            self.turn.update(ended=record.get("timestamp"), duration_s=round(millis / 1000, 1))
            self.done.append(self.turn)
            self.turn = None
        if self.turn is not None:
            self._note_pieces(line, record)

    def _note_pieces(self, line: str, record: dict) -> None:
        """Credit the open turn with the pieces this line shows it reading: a skill file named in a command, its
        output or the answer (`cat .agents/skills/athos-<id>/SKILL.md`), or a piece the hooks injected."""
        if "athos-" not in line and "`, v" not in line:
            return
        if not _is_catalog(record):
            self.turn["pieces"].update(SKILL_USE.findall(line))
        self.turn["pieces"].update(HOOK_USE.findall(line))

    def finish(self, path: Path) -> list[dict]:
        for turn in self.done:
            turn["session_id"] = self.meta.get("id", path.stem)
            turn["cwd"] = self.meta.get("cwd", "")
            turn["path"] = str(path)
        return self.done


def _session_turns(path: Path) -> list[dict]:
    """The completed turns of one Codex session file, each with its model, request, timing and the Athos pieces it
    used (read as skills or injected by the hooks)."""
    reader = _TurnReader()
    for line, record in _records(str(path)):
        reader.feed(line, record)
    return reader.finish(path)


def _rollout_files(root: Path) -> list[Path]:
    found = {*root.glob("**/rollout-*.jsonl"), *root.glob("**/rollout-*.jsonl.zst")} if root.is_dir() else set()
    return sorted(found)


def _task_events(task_id: str, turn: dict, used: list[str]) -> list[dict]:
    """The start/end pair the evaluation log keeps for one imported turn."""
    from athos.eval import request_fields
    project = Path(turn["cwd"]).name if turn["cwd"] else None
    start = {"type": "task_start", "task_id": task_id, "session_id": turn["session_id"], "platform": "codex",
             "model": turn["model"], "project": project, "at": turn["started"],
             **request_fields(turn["request"]), "source": "codex-import"}
    end = {"type": "task_end", "task_id": task_id, "session_id": turn["session_id"], "at": turn["ended"],
           "duration_s": turn["duration_s"], "tokens": tokens_between(turn["path"], turn["started"], turn["ended"]),
           "model": turn["model"], "pieces": used, "saved": []}
    return [start, end]


def _hook_recorded(event: dict) -> bool:
    """A task_start the Codex hooks wrote live (imported ones carry the `cx-` prefix)."""
    return (event.get("type") == "task_start" and event.get("platform") == "codex"
            and not str(event.get("task_id", "")).startswith(_IMPORTED))


def import_sessions(root: Path | None = None, include_tmp: bool = False) -> dict:
    """Copy Codex's past turns into the evaluation log (platform codex), straight from its session files.

    Safe to repeat: a turn already imported is not imported again, and a session the hooks recorded live is left to
    them. Unfinished turns, turns older than the store's `import-since`, and (unless `include_tmp`) sessions run in a
    temporary folder, as test runs are, are skipped. Returns counts of files read and turns imported or skipped."""
    from athos.eval import append as log_event, events as logged_events
    logged = logged_events()
    seen = {e.get("task_id") for e in logged}
    live = {e.get("session_id") for e in logged if _hook_recorded(e)}
    piece_ids = {p.id for p in store.all_pieces()}
    since = athos_paths.import_since()

    def skip(task_id: str, turn: dict) -> bool:
        return (task_id in seen or turn["session_id"] in live or not turn.get("ended")
                or bool(since and (turn.get("started") or "") < since)
                or (not include_tmp and turn["cwd"].startswith(TMP_PREFIXES)))

    counts = {"files": 0, "imported": 0, "skipped": 0}
    for file in _rollout_files(root or sessions_dir()):
        counts["files"] += 1
        for turn in _session_turns(file):
            task_id = f"{_IMPORTED}{turn['turn_id']}"
            if skip(task_id, turn):
                counts["skipped"] += 1
            else:
                used = sorted(piece for piece in turn["pieces"] if piece in piece_ids)
                for event in _task_events(task_id, turn, used):
                    log_event(event)
                seen.add(task_id)
                counts["imported"] += 1
    return counts
